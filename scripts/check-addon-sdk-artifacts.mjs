import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const root = resolve(".");
const distRoot = join(root, "dist");
const checksumPath = join(root, "SDK_ARTIFACTS.sha256");
const writeManifest = process.argv.includes("--write");

const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

async function collectArtifacts(directory) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return [];
    throw error;
  }

  const paths = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      paths.push(...(await collectArtifacts(path)));
      continue;
    }
    if (
      entry.name.endsWith(".js") ||
      entry.name.endsWith(".d.ts") ||
      entry.name.endsWith(".map")
    ) {
      paths.push(path);
    }
  }
  return paths;
}

const files = (await collectArtifacts(distRoot))
  .map((path) => relative(root, path).split("\\").join("/"))
  .sort();

for (const required of ["dist/index.js", "dist/index.d.ts"]) {
  if (!files.includes(required)) {
    throw new Error(`Missing generated SDK artifact: ${required}`);
  }
}

const lines = [];
for (const relativePath of files) {
  const bytes = await readFile(join(root, relativePath));
  const digest = createHash("sha256").update(bytes).digest("hex");
  lines.push(`${digest}  ${relativePath}`);
}

const checksumContents = [
  `# OPTN Wallet add-on SDK ${manifest.version} artifact checksums`,
  "# Generated by scripts/check-addon-sdk-artifacts.mjs --write",
  ...lines,
  "",
].join("\n");

if (writeManifest) {
  await writeFile(checksumPath, checksumContents, "utf8");
  console.log(`Wrote ${relative(root, checksumPath)}`);
} else {
  let recorded;
  try {
    recorded = await readFile(checksumPath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") {
      throw new Error(
        "Missing SDK_ARTIFACTS.sha256; run node scripts/check-addon-sdk-artifacts.mjs --write after building",
      );
    }
    throw error;
  }
  if (recorded !== checksumContents) {
    throw new Error(
      "SDK artifact checksum manifest is stale; rebuild and regenerate it before release review",
    );
  }
  console.log("SDK artifact checksum manifest is current.");
}

for (const line of lines) console.log(line);
